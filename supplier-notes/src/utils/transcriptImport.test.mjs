import test from 'node:test';
import assert from 'node:assert/strict';
import { parseTranscriptFile } from './transcriptImport.ts';

test('Teams WebVTT exports become speaker-labelled text with a duration', () => {
  const vtt = `﻿WEBVTT

NOTE generated by Teams

0f3e1d2a-1/12-0
00:00:01.200 --> 00:00:04.800
<v Nora Vale>We will send the BOM</v>

0f3e1d2a-1/13-0
00:00:04.900 --> 00:00:06.000
<v Nora Vale>by Tuesday.</v>

0f3e1d2a-2/1-0
00:00:06.500 --> 00:01:02.250
<v Eli Park>Fit check is the last gate &amp; then pilot.</v>
`;
  const result = parseTranscriptFile(vtt);
  assert.equal(result.text, 'Nora Vale: We will send the BOM by Tuesday.\nEli Park: Fit check is the last gate & then pilot.');
  assert.equal(result.duration, 62);
});

test('SRT subtitles and plain text are supported', () => {
  const srt = '1\r\n00:00:01,000 --> 00:00:03,000\r\nHello there\r\n\r\n2\r\n00:00:03,500 --> 00:00:05,000\r\nSecond line\r\n';
  assert.deepEqual(parseTranscriptFile(srt), { text: 'Hello there Second line', duration: 5 });
  assert.deepEqual(parseTranscriptFile('  Plain pasted transcript.\nLine two  '), { text: 'Plain pasted transcript.\nLine two', duration: 0 });
});
